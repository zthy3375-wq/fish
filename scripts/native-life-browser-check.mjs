import path from 'node:path';
/** Synthetic bridge/UI checks. Never calls provider accounts, SMS or transactions. */
export async function checkNativeLife(page,assert,{width,output}){
 await page.locator('.life-laundry').click();
 const dialog=page.getByRole('dialog',{name:'胖乖生活钱包'});
 await dialog.getByRole('button',{name:'连接胖乖生活',exact:true}).click();
 await dialog.getByText('人工测试商户',{exact:true}).waitFor();
 assert(await dialog.locator('.pg-balance').innerText().then(s=>s.includes('2.57')),`${width}: native Pangguai balance renders`);
 assert(await dialog.locator('.pg-merchant').filter({hasText:'人工测试商户'}).innerText().then(s=>s.includes('120.00')&&s.includes('点')),`${width}: merchant points retain independent units`);
 assert(!(await dialog.innerText()).includes('普通账户余额'),`${width}: general wallet is hidden`);
 assert(await page.locator('.life-laundry').innerText().then(s=>s.includes('2.57')&&!s.includes('18.50')),`${width}: home shortcut shows drinking-water balance`);
 assert(await page.evaluate(()=>(window.__pangguaiCalls??[]).length)===0,`${width}: wallet reads do not open official H5`);
 await dialog.locator('.pg-water-recharge').getByRole('button',{name:'充值',exact:true}).click();
 await dialog.getByRole('button',{name:'取消',exact:true}).click();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='openRecharge').length)===0,`${width}: recharge cancel never opens payment`);
 await dialog.getByRole('button',{name:'扫码识别设备',exact:true}).click();
 await dialog.getByRole('heading',{name:'人工测试设备'}).waitFor();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='scan').length)===1,`${width}: scanning is explicit and native`);
 assert(await dialog.locator('.wash-device').innerText().then(s=>s.includes('3.50')),`${width}: scan shows program price`);
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='startLaundry').length)===0,`${width}: scanning never starts a transaction`);
 await dialog.getByRole('radio',{name:/标准洗/}).check();
 await dialog.getByRole('button',{name:'查看费用',exact:true}).click();
 await dialog.getByRole('group',{name:'确认洗衣费用'}).waitFor();
 await dialog.getByRole('button',{name:'确认支付 ¥3.50 并洗衣',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(output,`laundry-confirm-${width}.png`),animations:'disabled'});
 await dialog.getByRole('group',{name:'确认洗衣费用'}).getByRole('button',{name:'取消',exact:true}).click();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='startLaundry').length)===0,`${width}: cancelling fee confirmation never pays`);
 await dialog.getByRole('button',{name:'查看费用',exact:true}).click();
 await dialog.getByRole('button',{name:'确认支付 ¥3.50 并洗衣',exact:true}).click();
 await dialog.getByRole('heading',{name:'已付款，等待启动确认'}).waitFor();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='startLaundry').length)===1,`${width}: explicit payment confirmation submits once`);
 await page.screenshot({path:path.join(output,`laundry-paid-${width}.png`),animations:'disabled'});
 await page.evaluate(()=>window.__pgWater=true);
 await dialog.getByRole('button',{name:'扫码识别设备',exact:true}).click();
 await dialog.getByRole('heading',{name:'人工测试饮水机',exact:true}).waitFor();
 await dialog.getByRole('button',{name:'接水',exact:true}).click();
 await dialog.getByRole('group',{name:'确认接水与扣费方式'}).waitFor();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='startWater').length)===0,`${width}: water preparation never unlocks`);
 await dialog.getByRole('button',{name:'确认开始接水',exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(output,`water-confirm-${width}.png`),animations:'disabled'});
 await dialog.getByRole('button',{name:'确认开始接水',exact:true}).click();
 await dialog.getByRole('heading',{name:'接水中',exact:true}).waitFor();
 assert(await page.evaluate(()=>window.__pgCalls.filter(c=>c.method==='startWater').length)===1,`${width}: confirmed water session starts once`);
 await dialog.getByRole('button',{name:'结束接水并结算',exact:true}).click();
 await dialog.getByRole('heading',{name:'等待设备结束',exact:true}).waitFor();
 assert(!(await dialog.locator('.water-progress').innerText()).includes('实付'),`${width}: end acknowledgement does not claim settlement`);
 await page.evaluate(()=>window.__pgWaterEnded=true);
 await dialog.locator('.water-progress').getByRole('button',{name:'查询状态',exact:true}).click();
 await dialog.locator('.water-history summary').filter({hasText:'本次接水已结算'}).waitFor();
 assert((await dialog.locator('.water-history').innerText()).includes('0.13'),`${width}: displays server-confirmed water bill`);
 await page.screenshot({path:path.join(output,`water-settled-${width}.png`),animations:'disabled'});
 await dialog.getByRole('tab',{name:'最近消费'}).click();
 await dialog.getByText('人工测试洗衣机',{exact:true}).waitFor();
 await page.evaluate(()=>window.__pgFailure=true);
 await dialog.getByRole('button',{name:'刷新胖乖余额与记录'}).click();
 await dialog.getByText(/余额未更新/).waitFor();
 assert(await dialog.locator('.pg-balance').innerText().then(s=>s.includes('2.57')),`${width}: failed native refresh preserves previous wallet`);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width}: native wallet fits viewport`);
 await page.screenshot({path:path.join(output,`native-wallet-${width}.png`),animations:'disabled'});
 await dialog.getByRole('button',{name:'关闭',exact:true}).click();
 await page.getByRole('button',{name:/校园地图/}).click();
 const map=page.getByRole('dialog',{name:'校园地图'});
 await map.getByRole('textbox',{name:'搜索教室',exact:true}).fill('A201');
 await map.locator('.rows button').filter({hasText:'A201'}).first().click();
 assert((await map.locator('.address').innerText()).includes('东区文理综合楼 · 2 层'),`${width}: verified room floor appears`);
 await map.getByRole('button',{name:'在平面图查看楼栋',exact:true}).click();
 await map.getByText('文理综合楼 A 区 · 楼栋参考点',{exact:true}).waitFor();
 const closeWidth=await map.locator('.plan .leaflet-image-layer').evaluate(img=>img.getBoundingClientRect().width);
 await map.getByRole('button',{name:'显示全图',exact:true}).click();
 assert(await map.locator('.plan .leaflet-image-layer').evaluate(img=>img.getBoundingClientRect().width)<closeWidth,`${width}: show whole plan actually zooms out`);
 await map.getByRole('button',{name:'查看这栋楼的教室',exact:true}).click();
 await map.getByText('正在查看 文理综合楼 A 区',{exact:false}).waitFor();
 assert((await map.locator('.rows strong').allTextContents()).every(name=>/^A\d/.test(name)),`${width}: plan opens only selected block rooms`);
 await map.getByLabel('筛选楼层',{exact:true}).selectOption('2');
 assert((await map.locator('.rows small').allTextContents()).every(text=>text.endsWith('2 层')),`${width}: plan room directory respects floor filter`);
 await map.getByRole('button',{name:'校园平面图',exact:true}).click();
 await map.getByRole('button',{name:'西校区平面图',exact:true}).click();
 await map.locator('.plan .leaflet-image-layer').waitFor();
 await page.waitForFunction(()=>{const img=document.querySelector('.plan .leaflet-image-layer');return img instanceof HTMLImageElement&&img.complete&&img.naturalWidth===864});
 assert(await map.locator('.plan .leaflet-image-layer').evaluate(img=>img.complete&&img.naturalWidth===864),`${width}: provided west plan loaded`);
 await page.screenshot({path:path.join(output,`campus-plan-${width}.png`),animations:'disabled'});
 await map.getByRole('button',{name:'道路与地点',exact:true}).click();
 await map.locator('.leaflet-container').waitFor();
 await map.getByRole('button',{name:'西校区',exact:true}).click();
 await map.getByRole('textbox',{name:'搜索校园地点'}).fill('二教');
 assert(await map.locator('.map-list button').count()===1,`${width}: map filters real sourced places`);
 await map.locator('.map-list button').click();
 await map.getByRole('button',{name:'收藏地点',exact:true}).click();
 await map.getByRole('textbox',{name:'搜索校园地点'}).fill('');
 await map.getByRole('button',{name:'收藏',exact:true}).click();
 assert(await map.locator('.map-list button').count()===1,`${width}: map favorites filter persists`);
 await map.getByRole('button',{name:'添加地点',exact:true}).click();
 await map.locator('.map-canvas').click({position:{x:140,y:160}});
 await map.getByRole('textbox',{name:'名称',exact:true}).fill('人工地图测试地点');
 await map.getByRole('button',{name:'保存地点',exact:true}).click();
 assert(await page.evaluate(()=>JSON.parse(localStorage.getItem('handan-campus-map-v083')).places.length)===1,`${width}: map saves a personal place without replacing provider data`);
 assert(await map.locator('iframe').count()===0,`${width}: map is app-owned rather than embedded provider page`);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${width}: campus map fits viewport`);
 await page.screenshot({path:path.join(output,`campus-map-${width}.png`),animations:'disabled'});
 await map.getByRole('button',{name:'关闭',exact:true}).click();
}
